import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build, version as esbuildVersion } from 'esbuild';

const root = fileURLToPath(new URL('..', import.meta.url));
const vendor = 'shared/vendor';
const entry = "export { XMLValidator } from 'fast-xml-parser'; export { Parser } from 'htmlparser2';";
const digest = (value: string | Uint8Array) => createHash('sha256').update(value).digest('hex');

/** Bundles public ESM exports unchanged; never aliases or patches denied globals. */
export async function buildNativeParser(check = false): Promise<void> {
  const lock = JSON.parse(await readFile(resolve(root, 'package-lock.json'), 'utf8'));
  assert.equal(lock.packages['node_modules/fast-xml-parser'].version, '5.11.2');
  assert.equal(lock.packages['node_modules/htmlparser2'].version, '12.0.0');
  assert.equal(esbuildVersion, '0.28.2');
  const result = await build({
    absWorkingDir: root,
    stdin: { contents: entry, resolveDir: root, sourcefile: 'native-parser-vendor-entry.js' },
    bundle: true, format: 'esm', platform: 'browser', target: 'es2022',
    write: false, metafile: true, minify: false, legalComments: 'inline', treeShaking: true,
  });
  const code = '// Generated by npm run build:native-parser. Do not edit.\n' +
    '// Unmodified upstream ESM: see feed-parsers.provenance.json and LICENSES.txt.\n' + result.outputFiles[0].text;
  // A future upstream release cannot quietly change this into a Node/CJS shim.
  assert.equal(result.metafile.outputs[Object.keys(result.metafile.outputs)[0]].imports.length, 0);
  const included = new Set<string>();
  for (const output of Object.values(result.metafile.outputs)) {
    for (const [input, contribution] of Object.entries(output.inputs)) {
      if (contribution.bytesInOutput > 0 && input.startsWith('node_modules/')) included.add(input);
    }
  }
  const packageRoots = new Set<string>();
  const sources = [];
  for (const source of [...included].sort()) {
    const segments = source.split('/');
    const index = segments.lastIndexOf('node_modules');
    packageRoots.add(segments.slice(0, index + (segments[index + 1].startsWith('@') ? 3 : 2)).join('/'));
    sources.push({ path: source, sha256: digest(await readFile(resolve(root, source))) });
  }
  const packages = [];
  const licenses = [];
  for (const packageRoot of [...packageRoots].sort()) {
    const manifest = JSON.parse(await readFile(resolve(root, packageRoot, 'package.json'), 'utf8'));
    const locked = lock.packages[packageRoot];
    assert.equal(manifest.version, locked.version, `Installed ${manifest.name} must match package-lock.json`);
    assert.ok(['MIT', 'BSD-2-Clause'].includes(manifest.license));
    packages.push({ name: manifest.name, version: manifest.version, license: manifest.license, repository: manifest.repository, resolved: locked.resolved, integrity: locked.integrity });
    licenses.push(`${manifest.name} ${manifest.version}\n${await readFile(resolve(root, packageRoot, 'LICENSE'), 'utf8')}`);
  }
  const provenance = {
    generatedBy: 'scripts/build-native-parser.ts',
    command: 'npm ci && npm run build:native-parser',
    toolchain: { esbuild: esbuildVersion, target: 'es2022', platform: 'browser', format: 'esm' },
    entry,
    note: 'Only XMLValidator, htmlparser2 Parser and its entities decoder survive tree-shaking. No upstream patches, aliases, defines or global shims are used. fast-xml-parser XMLParser is deliberately not imported because strnum uses unsupported window fallback.',
    outputSha256: digest(code), packages, sources,
  };
  const artifacts = {
    'feed-parsers.js': code,
    'feed-parsers.provenance.json': `${JSON.stringify(provenance, null, 2)}\n`,
    'LICENSES.txt': `${licenses.join('\n\n-----\n\n')}\n`,
  };
  if (!check) await mkdir(resolve(root, vendor), { recursive: true });
  for (const [name, content] of Object.entries(artifacts)) {
    const path = resolve(root, vendor, name);
    if (check) assert.equal(await readFile(path, 'utf8'), content, `Stale ${vendor}/${name}; run npm run build:native-parser`);
    else await writeFile(path, content);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildNativeParser(process.argv.includes('--check'));
  console.log(`Native parser vendor artifacts ${process.argv.includes('--check') ? 'verified' : 'generated'} from locked, unmodified registry packages.`);
}
